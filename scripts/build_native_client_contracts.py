#!/usr/bin/env python3
"""Generate minimal TypeScript, Kotlin and Swift types from the shared model."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "research/shared-evidence-model.json"
OUT = ROOT / "clients/generated"


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]+", name) if part)


def fields(model: dict) -> list[tuple[str, list[str]]]:
    return [(name, list(spec.get("required", []))) for name, spec in model["entity_types"].items()]


def build(model: dict) -> dict[str, str]:
    entities = fields(model)
    entity_names = [pascal(name) for name, _ in entities]
    ts = [
        "// Generated by scripts/build_native_client_contracts.py; do not edit.",
        f"export const SHARED_MODEL_ID = {model['model_id']!r};",
        "export type ClaimLevel = 'source_observation' | 'contextual_interpretation' | 'candidate_mechanism' | 'provisional_pattern' | 'practice_hypothesis' | 'learning_evidence' | 'listener_outcome_evidence';",
        "export type RecordValue = string | number | boolean | string[] | Record<string, unknown> | null;",
    ]
    for name, required in entities:
        ts.append(f"export interface {pascal(name)} {{")
        for key in required:
            ts.append(f"  {key}: RecordValue;")
        ts.append("}")
    ts += [f"export type SharedEvidenceEntity = {' | '.join(entity_names)};", ""]

    kt = [
        "// Generated by scripts/build_native_client_contracts.py; do not edit.",
        f'const val SHARED_MODEL_ID = "{model["model_id"]}"',
        "typealias RecordValue = Any?",
    ]
    for name, required in entities:
        kt.append(f"data class {pascal(name)}(")
        kt.extend(f"    val {key}: RecordValue," for key in required)
        kt.append(")")
    kt.append("")

    swift = [
        "// Generated by scripts/build_native_client_contracts.py; do not edit.",
        "import Foundation",
        f'public let sharedModelID = "{model["model_id"]}"',
        "public indirect enum RecordValue: Codable {",
        "    case string(String), number(Double), boolean(Bool), array([RecordValue]), object([String: RecordValue]), null",
        "    public init(from decoder: Decoder) throws {",
        "        let container = try decoder.singleValueContainer()",
        "        if container.decodeNil() { self = .null }",
        "        else if let value = try? container.decode(String.self) { self = .string(value) }",
        "        else if let value = try? container.decode(Double.self) { self = .number(value) }",
        "        else if let value = try? container.decode([RecordValue].self) { self = .array(value) }",
        "        else if let value = try? container.decode([String: RecordValue].self) { self = .object(value) }",
        "        else { self = .boolean(try container.decode(Bool.self)) }",
        "    }",
        "    public func encode(to encoder: Encoder) throws {",
        "        var container = encoder.singleValueContainer()",
        "        switch self { case .string(let value): try container.encode(value); case .number(let value): try container.encode(value); case .boolean(let value): try container.encode(value); case .array(let value): try container.encode(value); case .object(let value): try container.encode(value); case .null: try container.encodeNil() }",
        "    }",
        "}",
    ]
    for name, required in entities:
        swift.append(f"public struct {pascal(name)}: Codable {{")
        for key in required:
            swift.append(f"    public let {key}: RecordValue")
        swift.append("}")
    swift.append("")
    kotlin_helper = [
        "// Generated by scripts/build_native_client_contracts.py; do not edit.",
        "@Suppress(\"UNCHECKED_CAST\")",
        "object MobileLessonHelpers {",
        "    fun selectLessonStep(lesson: Map<String, Any?>, stepId: String): Map<String, Any?> {",
        "        require(lesson[\"status\"] == \"provisional_not_validated\") { \"lesson is not a provisional lesson\" }",
        "        require(lesson[\"claim_level\"] == \"practice_hypothesis\") { \"lesson is not a practice hypothesis\" }",
        "        require((lesson[\"safety_boundary\"] as? String)?.trim()?.isNotEmpty() == true) { \"lesson safety boundary is required\" }",
        "        val steps = lesson[\"steps\"] as? List<Map<String, Any?>> ?: error(\"lesson steps are missing\")",
        "        return steps.firstOrNull { it[\"step_id\"] == stepId } ?: error(\"lesson step not found: $stepId\")",
        "    }",
        "    fun linkedEvidenceIds(lesson: Map<String, Any?>): List<String> {",
        "        val links = lesson[\"evidence_links\"] as? Map<String, Any?> ?: return emptyList()",
        "        return (links[\"exact_example_ids\"] as? List<*>)?.filterIsInstance<String>()?.distinct()?.sorted() ?: emptyList()",
        "    }",
        "    fun createPracticeRecord(lesson: Map<String, Any?>, participantCode: String, accessibilityOrModality: String, stepResponses: Map<String, String>, savedAt: String): Map<String, Any?> {",
        "        require(participantCode.trim().isNotEmpty()) { \"participant code is required\" }",
        "        require(lesson[\"status\"] == \"provisional_not_validated\") { \"lesson is not a provisional lesson\" }",
        "        require(lesson[\"claim_level\"] == \"practice_hypothesis\") { \"lesson is not a practice hypothesis\" }",
        "        require((lesson[\"safety_boundary\"] as? String)?.trim()?.isNotEmpty() == true) { \"lesson safety boundary is required\" }",
        "        val links = lesson[\"evidence_links\"] as? Map<String, Any?> ?: error(\"lesson evidence links are missing\")",
        "        return mapOf(\"record_type\" to \"local_communication_practice_record\", \"schema_version\" to \"1.0\", \"lesson_id\" to lesson[\"lesson_id\"], \"pattern_id\" to lesson[\"pattern_id\"], \"canonical_job\" to lesson[\"canonical_job\"], \"source_evidence_ids\" to (links[\"exact_example_ids\"] ?: emptyList<String>()), \"delivery_sample_ids\" to (links[\"delivery_sample_ids\"] ?: emptyList<String>()), \"participant_code\" to participantCode, \"consent\" to true, \"accessibility_or_modality\" to accessibilityOrModality, \"step_responses\" to stepResponses, \"claim_boundary\" to \"Local practice log only; not learner-validation evidence or effectiveness evidence.\", \"saved_at\" to savedAt)",
        "    }",
        "    fun changedResponses(previous: Map<String, Any?>, latest: Map<String, Any?>): List<String> {",
        "        val before = previous[\"step_responses\"] as? Map<*, *> ?: emptyMap<Any?, Any?>()",
        "        val after = latest[\"step_responses\"] as? Map<*, *> ?: emptyMap<Any?, Any?>()",
        "        return (before.keys.filterIsInstance<String>() + after.keys.filterIsInstance<String>()).distinct().filter { before[it] != after[it] }.sorted()",
        "    }",
        "}",
        "",
    ]
    swift_helper = [
        "// Generated by scripts/build_native_client_contracts.py; do not edit.",
        "import Foundation",
        "public enum MobileLessonHelpers {",
        "    public static func selectLessonStep(_ lesson: [String: Any], stepId: String) throws -> [String: Any] {",
        "        guard (lesson[\"status\"] as? String) == \"provisional_not_validated\" else { throw LessonHelperError.invalidStatus }",
        "        guard (lesson[\"claim_level\"] as? String) == \"practice_hypothesis\" else { throw LessonHelperError.invalidClaimLevel }",
        "        guard let safety = lesson[\"safety_boundary\"] as? String, !safety.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { throw LessonHelperError.missingSafetyBoundary }",
        "        guard let steps = lesson[\"steps\"] as? [[String: Any]], let step = steps.first(where: { ($0[\"step_id\"] as? String) == stepId }) else { throw LessonHelperError.stepNotFound(stepId) }",
        "        return step",
        "    }",
        "    public static func linkedEvidenceIds(_ lesson: [String: Any]) -> [String] {",
        "        guard let links = lesson[\"evidence_links\"] as? [String: Any], let ids = links[\"exact_example_ids\"] as? [String] else { return [] }",
        "        return Array(Set(ids)).sorted()",
        "    }",
        "    public static func createPracticeRecord(_ lesson: [String: Any], participantCode: String, accessibilityOrModality: String, stepResponses: [String: String], savedAt: String) throws -> [String: Any] {",
        "        guard !participantCode.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { throw LessonHelperError.missingParticipantCode }",
        "        guard (lesson[\"status\"] as? String) == \"provisional_not_validated\" else { throw LessonHelperError.invalidStatus }",
        "        guard (lesson[\"claim_level\"] as? String) == \"practice_hypothesis\" else { throw LessonHelperError.invalidClaimLevel }",
        "        guard let safety = lesson[\"safety_boundary\"] as? String, !safety.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { throw LessonHelperError.missingSafetyBoundary }",
        "        guard let links = lesson[\"evidence_links\"] as? [String: Any] else { throw LessonHelperError.missingEvidenceLinks }",
        "        return [\"record_type\": \"local_communication_practice_record\", \"schema_version\": \"1.0\", \"lesson_id\": lesson[\"lesson_id\"] as Any, \"pattern_id\": lesson[\"pattern_id\"] as Any, \"canonical_job\": lesson[\"canonical_job\"] as Any, \"source_evidence_ids\": links[\"exact_example_ids\"] ?? [], \"delivery_sample_ids\": links[\"delivery_sample_ids\"] ?? [], \"participant_code\": participantCode, \"consent\": true, \"accessibility_or_modality\": accessibilityOrModality, \"step_responses\": stepResponses, \"claim_boundary\": \"Local practice log only; not learner-validation evidence or effectiveness evidence.\", \"saved_at\": savedAt]",
        "    }",
        "    public static func changedResponses(_ previous: [String: Any], _ latest: [String: Any]) -> [String] {",
        "        let before = previous[\"step_responses\"] as? [String: String] ?? [:], after = latest[\"step_responses\"] as? [String: String] ?? [:]",
        "        return Set(before.keys).union(after.keys).filter { before[$0] != after[$0] }.sorted()",
        "    }",
        "    public enum LessonHelperError: Error { case invalidStatus, invalidClaimLevel, missingSafetyBoundary, stepNotFound(String), missingParticipantCode, missingEvidenceLinks }",
        "}",
        "",
    ]
    return {
        "clients/generated/shared_evidence_contract.ts": "\n".join(ts),
        "clients/generated/SharedEvidenceContract.kt": "\n".join(kt),
        "clients/generated/SharedEvidenceContract.swift": "\n".join(swift),
        "clients/examples/MobileLessonHelpers.kt": "\n".join(kotlin_helper),
        "clients/examples/MobileLessonHelpers.swift": "\n".join(swift_helper),
    }


def main() -> int:
    model = json.loads(MODEL.read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    outputs = build(model)
    for relative, content in outputs.items():
        path = ROOT / relative
        path.write_text(content + "\n")
    print(f"native client contracts generated: {len(outputs)} files, {len(model['entity_types'])} entities")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
